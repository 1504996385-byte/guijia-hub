"""Import three user-supplied MP3 prompts locally, without gain or loudness filters.

Only versioned WAV files and the three const C assets are written. Provenance
and measured metadata are retained in generated C comments; no ASR is run.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import wave
import zlib

ROOT = Path(__file__).resolve().parents[1]
PROMPTS = (
    ('arrival', 'arrive', '欢迎回家.mp3'),
    ('reminder', 'take_key', '出门提醒.mp3'),
    ('departure', 'leave', '一路顺风.mp3'),
)


def find_ffmpeg(explicit):
    if explicit:
        result = Path(explicit).resolve()
    elif shutil.which('ffmpeg'):
        result = Path(shutil.which('ffmpeg')).resolve()
    else:
        try:
            import imageio_ffmpeg
            result = Path(imageio_ffmpeg.get_ffmpeg_exe()).resolve()
        except (ImportError, RuntimeError):
            raise SystemExit('No local ffmpeg found; pass --ffmpeg PATH.') from None
    if not result.is_file():
        raise SystemExit('The ffmpeg executable does not exist.')
    return result


def digest(data):
    return hashlib.sha256(data).hexdigest()


def convert(ffmpeg, source):
    # A list of arguments, never a shell. No -af, volume, loudnorm or dynaudnorm.
    command = [str(ffmpeg), '-nostdin', '-hide_banner', '-loglevel', 'info',
               '-i', str(source), '-map', '0:a:0', '-vn', '-sn', '-dn',
               '-map_metadata', '-1', '-ac', '1', '-ar', '16000',
               '-c:a', 'pcm_s16le', '-f', 's16le', 'pipe:1']
    result = subprocess.run(command, capture_output=True, timeout=90)
    if result.returncode:
        # Do not print arbitrary embedded MP3 metadata or decoder diagnostics.
        raise SystemExit('Local ffmpeg conversion failed; no asset was written.')
    pcm = result.stdout
    if not pcm or len(pcm) % 2 or len(pcm) > 16000 * 2 * 30:
        raise SystemExit('Decoded PCM must be nonempty, aligned and at most 30 seconds.')
    input_info = result.stderr.decode('utf-8', errors='replace').split('Output #', 1)[0]
    stream = re.search(r'Audio:\s*([^,\r\n]+),\s*(\d+) Hz,\s*([^,\r\n]+),\s*([^,\r\n]+)', input_info)
    if not stream:
        raise SystemExit('Source audio format could not be established.')
    source_format = dict(codec=stream[1].strip(), sample_rate=int(stream[2]),
                         channel_layout=stream[3].strip(), sample_format=stream[4].strip())
    output = io.BytesIO()
    with wave.open(output, 'wb') as wav:
        wav.setparams((1, 2, 16000, len(pcm)//2, 'NONE', 'not compressed'))
        wav.writeframes(pcm)
    payload = output.getvalue()
    if len(payload) != 44 + len(pcm) or payload[36:40] != b'data':
        raise SystemExit('Canonical WAV header generation failed.')
    with wave.open(io.BytesIO(payload), 'rb') as wav:
        if ((wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getcomptype())
                != (1, 2, 16000, 'NONE') or wav.readframes(wav.getnframes()) != pcm):
            raise SystemExit('WAV validation failed.')
    return payload, pcm, source_format


def emit_asset(role, payload, metadata, version):
    upper = role.upper()
    prefix = 'hh_' + role + '_wav'
    checksum = 2166136261
    for byte in payload:
        checksum = ((checksum ^ byte) * 16777619) & 0xffffffff
    crc = zlib.crc32(payload) & 0xffffffff
    metadata.update(bytes=len(payload), sha256=digest(payload),
                    checksum_fnv1a=f'{checksum:08x}', crc32=f'{crc:08x}')
    header = f'''/* Generated by scripts/import-prompt-audio.py; user-supplied audio. */
#ifndef HOMEHUB_{upper}_ASSET_H
#define HOMEHUB_{upper}_ASSET_H
#include <stdint.h>
#define HH_{upper}_ASSET_VERSION {version}u
#define HH_{upper}_WAV_BYTES {len(payload)}u
extern const uint8_t {prefix}[HH_{upper}_WAV_BYTES];
extern const uint32_t {prefix}_size;
/* FNV-1a, identical to hh_checksum; CRC32 is the standard reflected form. */
extern const uint32_t {prefix}_checksum;
extern const uint32_t {prefix}_crc32;
extern const char {prefix}_sha256[65];
#endif
'''
    source = ['/* Generated by scripts/import-prompt-audio.py.\n',
              ' * User-supplied MP3 converted locally; no gain/loudness processing.\n',
              ' * No ASR, transcript decoding or semantic verification performed.\n',
              ' * Metadata: ' + json.dumps(metadata, ensure_ascii=False, sort_keys=True) + '\n',
              ' */\n', f'#include "homehub_{role}_asset.h"\n',
              f'const uint8_t {prefix}[HH_{upper}_WAV_BYTES] = {{\n']
    source.extend('    ' + ','.join(f'0x{byte:02x}' for byte in payload[n:n+16]) + ',\n'
                  for n in range(0, len(payload), 16))
    source.append(f'''}};
const uint32_t {prefix}_size = sizeof({prefix});
const uint32_t {prefix}_checksum = UINT32_C(0x{checksum:08x});
const uint32_t {prefix}_crc32 = UINT32_C(0x{crc:08x});
const char {prefix}_sha256[65] = "{digest(payload)}";
''')
    return header, ''.join(source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', required=True, type=Path)
    parser.add_argument('--ffmpeg', type=Path)
    parser.add_argument('--version', default=3, type=int)
    args = parser.parse_args()
    if not 3 <= args.version <= 9999:
        raise SystemExit('Imported prompt versions start at 3.')
    ffmpeg = find_ffmpeg(args.ffmpeg)
    tool_sha = digest(ffmpeg.read_bytes())
    prepared = []
    for role, stem, filename in PROMPTS:
        original = args.source_dir.resolve() / filename
        original_bytes = original.read_bytes()
        payload, pcm, source_format = convert(ffmpeg, original)
        if original.read_bytes() != original_bytes:
            raise SystemExit('A source MP3 changed during conversion; import aborted.')
        samples = struct.unpack('<' + 'h' * (len(pcm)//2), pcm)
        metadata = dict(role=role, version=args.version, source_file=filename,
                        source_bytes=len(original_bytes), source_sha256=digest(original_bytes),
                        source_format=source_format, ffmpeg_sha256=tool_sha,
                        format='PCM S16LE', sample_rate=16000, bits=16, channels=1,
                        frames=len(samples), duration_seconds=len(samples)/16000,
                        peak=max(abs(sample) for sample in samples),
                        clipped_samples=sum(sample in (-32768, 32767) for sample in samples),
                        gain_or_loudness_processing=False, asr_verified=False)
        header, source = emit_asset(role, payload, metadata, args.version)
        prepared.append((role, stem, payload, header, source, metadata))
    # Decode/validate all three before writing any resource. Legacy and v2 paths
    # are never destinations, even when this importer is run again.
    for role, stem, payload, header, source, metadata in prepared:
        wav_path = ROOT / f'sdcard/homehub/voices/{stem}_v{args.version}.wav'
        header_path = ROOT / f'firmware/src/homehub_{role}_asset.h'
        source_path = ROOT / f'firmware/src/homehub_{role}_asset.c'
        wav_path.write_bytes(payload)
        header_path.write_text(header, encoding='utf-8')
        source_path.write_text(source, encoding='utf-8')
        actual = source_path.read_text(encoding='utf-8')
        array = re.search(r'const uint8_t ' + re.escape('hh_'+role+'_wav')
                          + r'\[[^\]]+\] = \{\n(.*?)\n\};', actual, re.S)
        embedded = bytes(int(value, 16) for value in re.findall(r'0x([0-9a-f]{2})', array[1]))
        if embedded != wav_path.read_bytes() or digest(embedded) != metadata['sha256']:
            raise SystemExit('Generated C array differs from its canonical WAV.')
    print(json.dumps([item[-1] for item in prepared], ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
