"""Normalize and embed only the local-speech v2 reminder, never legacy voices."""
from pathlib import Path
import hashlib
import io
import json
import struct
import wave
import zlib

ROOT = Path(__file__).resolve().parents[1]
WAV = ROOT / 'sdcard/homehub/voices/take_key_v2.wav'
HEADER = ROOT / 'firmware/src/homehub_reminder_asset.h'
SOURCE = ROOT / 'firmware/src/homehub_reminder_asset.c'
TEXT = '主人，出门请带好钥匙，关好水电燃气门窗。'


def main():
    raw = WAV.read_bytes()
    with wave.open(io.BytesIO(raw), 'rb') as audio:
        if (audio.getnchannels(), audio.getsampwidth(), audio.getframerate(), audio.getcomptype()) != (1, 2, 16000, 'NONE'):
            raise SystemExit('Reminder must be uncompressed 16 kHz / 16 bit / mono PCM.')
        frames = audio.getnframes()
        if not 0 < frames <= 16000 * 30:
            raise SystemExit('Reminder duration must be positive and at most 30 seconds.')
        pcm = audio.readframes(frames)
        if len(pcm) != frames * 2:
            raise SystemExit('Truncated reminder PCM.')
    # Remove System.Speech metadata chunks and emit the exact canonical layout
    # required by the existing hh_wav_validate, without altering PCM samples.
    output = io.BytesIO()
    with wave.open(output, 'wb') as normalized:
        normalized.setparams((1, 2, 16000, frames, 'NONE', 'not compressed'))
        normalized.writeframes(pcm)
    payload = output.getvalue()
    if len(payload) != 44 + len(pcm) or payload[36:40] != b'data':
        raise SystemExit('Unexpected canonical WAV layout.')
    sha256 = hashlib.sha256(payload).hexdigest()
    crc32 = zlib.crc32(payload) & 0xffffffff
    checksum = 2166136261
    for byte in payload:
        checksum = ((checksum ^ byte) * 16777619) & 0xffffffff
    header = f'''/* Generated by scripts/embed-reminder-asset.py; local synthetic Mandarin. */
#ifndef HOMEHUB_REMINDER_ASSET_H
#define HOMEHUB_REMINDER_ASSET_H
#include <stdint.h>
#define HH_REMINDER_ASSET_VERSION 2u
#define HH_REMINDER_WAV_BYTES {len(payload)}u
extern const uint8_t hh_reminder_wav[HH_REMINDER_WAV_BYTES];
extern const uint32_t hh_reminder_wav_size;
/* FNV-1a, identical to the existing hh_checksum used by the TF installer. */
extern const uint32_t hh_reminder_wav_checksum;
extern const uint32_t hh_reminder_wav_crc32;
extern const char hh_reminder_wav_sha256[65];
#endif
'''
    parts = [f'''/* Generated by scripts/embed-reminder-asset.py.
 * Local Windows System.Speech synthetic Mandarin, not family/dialect audio.
 * Text: {TEXT}
 * Only this v2 reminder is embedded; legacy prompts remain TF-only.
 * SHA256: {sha256}
 */
#include "homehub_reminder_asset.h"
const uint8_t hh_reminder_wav[HH_REMINDER_WAV_BYTES] = {{
''']
    parts.extend('    ' + ','.join(f'0x{byte:02x}' for byte in payload[n:n+16]) + ',\n'
                 for n in range(0, len(payload), 16))
    parts.append(f'''}};
const uint32_t hh_reminder_wav_size = sizeof(hh_reminder_wav);
const uint32_t hh_reminder_wav_checksum = UINT32_C(0x{checksum:08x});
const uint32_t hh_reminder_wav_crc32 = UINT32_C(0x{crc32:08x});
const char hh_reminder_wav_sha256[65] = "{sha256}";
''')
    WAV.write_bytes(payload)
    HEADER.write_text(header, encoding='utf-8')
    SOURCE.write_text(''.join(parts), encoding='utf-8')
    samples = struct.unpack('<' + 'h' * frames, pcm)
    print(json.dumps(dict(file=str(WAV), text=TEXT, bytes=len(payload),
                         sample_rate=16000, bits=16, channels=1,
                         frames=frames, duration_seconds=frames/16000,
                         peak=max(abs(sample) for sample in samples),
                         clipped_samples=sum(sample in (-32768, 32767) for sample in samples),
                         checksum_fnv1a=f'{checksum:08x}', crc32=f'{crc32:08x}',
                         sha256=sha256, source='local Windows System.Speech'),
                     ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
